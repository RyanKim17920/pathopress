#!/usr/bin/env python3
"""Run threshold, complete-submatrix SVD, and pairwise-correlation analyses."""

from __future__ import annotations

import csv
import hashlib
import json
import sys
from pathlib import Path

import numpy as np


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from pathopress.matrix import filter_matrix, load_scores, make_matrix  # noqa: E402
from pathopress.structure import (  # noqa: E402
    best_neighbor_ols,
    classical_mds_from_correlations,
    complete_submatrix_for_count,
    find_largest_complete_submatrix,
    pairwise_correlations,
    singular_summary,
)


OUTPUT = ROOT / "experiments" / "structure_analysis"


def _write_json(path: Path, payload) -> None:
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def threshold_rows(matrix: np.ndarray, models: list[str], evaluations: list[str]):
    grids = {
        "upstream_exact": [(m, b) for m in (10, 15, 20) for b in (8, 12, 16)],
        "pathology_scaled": [(m, b) for m in (2, 3, 5) for b in (3, 5, 8)],
    }
    output = {}
    for grid_name, pairs in grids.items():
        rows = []
        for model_threshold, evaluation_threshold in pairs:
            filtered, selected_models, selected_evaluations = filter_matrix(
                matrix, models, evaluations,
                min_scores_per_model=model_threshold,
                min_models_per_evaluation=evaluation_threshold,
            )
            rows.append(
                {
                    "min_scores_per_model": model_threshold,
                    "min_models_per_evaluation": evaluation_threshold,
                    "n_models": len(selected_models),
                    "n_evaluations": len(selected_evaluations),
                    "n_observations": int(np.isfinite(filtered).sum()),
                    "fill_rate": float(np.isfinite(filtered).mean()) if filtered.size else 0.0,
                    "is_pathology_selected": (model_threshold, evaluation_threshold) == (3, 5),
                }
            )
        output[grid_name] = rows
    return output


def threshold_latex(payload: dict) -> str:
    rows = payload["pathology_scaled"]
    lines = [
        "% Auto-generated by experiments/run_structure_analysis.py",
        r"\begin{tabular}{rr cccc}", r"\toprule",
        r"$T_M$ & $T_E$ & \#Models & \#Eval. & \#Obs. & Fill \\", r"\midrule",
    ]
    for row in rows:
        cells = (
            row["min_scores_per_model"], row["min_models_per_evaluation"], row["n_models"],
            row["n_evaluations"], f"{row['n_observations']:,}", f"{100 * row['fill_rate']:.1f}\\%",
        )
        text = " & ".join(map(str, cells))
        if row["is_pathology_selected"]:
            text = r"\textbf{" + text.replace(" & ", r"} & \textbf{") + "}"
        lines.append(text + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    return "\n".join(lines) + "\n"


def svd_latex(rows: list[dict]) -> str:
    lines = [
        "% Auto-generated by experiments/run_structure_analysis.py",
        r"\begin{tabular}{ccccc}", r"\toprule",
        r"\textbf{\# Eval.} & \textbf{\# Models} & \textbf{Stable rank} & \textbf{Var (top 1)} & \textbf{Var (top 2)} \\",
        r"\midrule",
    ]
    for row in rows:
        lines.append(
            f"{row['n_evaluations']} & {row['n_models']} & {row['stable_rank']:.2f} & "
            f"{100 * row['var_rank1']:.1f}\\% & {100 * row['var_rank2']:.1f}\\% \\\\"
        )
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    return "\n".join(lines) + "\n"


def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    scores_path = ROOT / "data" / "scores.csv"
    scores = load_scores(scores_path)
    raw_matrix, raw_models, raw_evaluations = make_matrix(scores)
    matrix, models, evaluations = filter_matrix(raw_matrix, raw_models, raw_evaluations)
    suite_by_evaluation = {}
    for score in scores:
        if score.evaluation_id in evaluations:
            suite_by_evaluation.setdefault(score.evaluation_id, score.suite_id)

    thresholds = threshold_rows(raw_matrix, raw_models, raw_evaluations)
    threshold_payload = {
        "schema_version": 1,
        "description": "Iterated minimum-observation threshold sensitivity",
        "unfiltered": {
            "n_models": len(raw_models), "n_evaluations": len(raw_evaluations),
            "n_observations": int(np.isfinite(raw_matrix).sum()),
            "fill_rate": float(np.isfinite(raw_matrix).mean()),
        },
        "grids": thresholds,
        "pathology_adaptation": "BenchPress 10/15/20 x 8/12/16 grid is retained; a 2/3/5 x 3/5/8 grid is added around PathoPress's selected 3 x 5 threshold.",
    }
    _write_json(OUTPUT / "threshold_sweep.json", threshold_payload)
    (OUTPUT / "threshold_sweep.tex").write_text(
        threshold_latex(thresholds), encoding="utf-8"
    )

    largest_rows, largest_columns = find_largest_complete_submatrix(matrix, min_evaluations=5)
    largest_summary = singular_summary(matrix[np.ix_(largest_rows, largest_columns)])
    stable_rank_payload = {
        "schema_version": 1,
        "complete_submatrix_shape": [len(largest_rows), len(largest_columns)],
        "model_ids": [models[index] for index in largest_rows],
        "evaluation_ids": [evaluations[index] for index in largest_columns],
        **largest_summary,
    }
    _write_json(OUTPUT / "stable_rank_results.json", stable_rank_payload)
    sweep_rows = []
    for count in (4, 7, 10, 13):
        rows, columns = complete_submatrix_for_count(matrix, count)
        summary = singular_summary(matrix[np.ix_(rows, columns)])
        sweep_rows.append(
            {
                "n_evaluations": len(columns), "n_models": len(rows),
                "model_ids": [models[index] for index in rows],
                "evaluation_ids": [evaluations[index] for index in columns],
                **summary,
            }
        )
    _write_json(OUTPUT / "submatrix_sweep.json", sweep_rows)
    (OUTPUT / "submatrix_sweep.tex").write_text(svd_latex(sweep_rows), encoding="utf-8")

    pairwise = best_neighbor_ols(matrix, evaluations, min_shared=5)
    for evaluation, row in pairwise.items():
        row["suite_id"] = suite_by_evaluation[evaluation]
        row["best_neighbor_suite_id"] = suite_by_evaluation[row["best_neighbor"]]
    _write_json(OUTPUT / "pairwise_ols_stats.json", pairwise)
    correlations, counts, _means, _stds = pairwise_correlations(matrix, min_shared=5)
    coordinates = classical_mds_from_correlations(correlations)
    np.savez_compressed(
        OUTPUT / "correlation_mds.npz",
        correlations=correlations,
        shared_counts=counts,
        coordinates=coordinates,
        evaluation_ids=np.asarray(evaluations),
    )
    with (OUTPUT / "mds_coordinates.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(("evaluation_id", "suite_id", "mds_dimension_1", "mds_dimension_2"))
        for evaluation, coordinate in zip(evaluations, coordinates):
            writer.writerow((evaluation, suite_by_evaluation[evaluation], coordinate[0], coordinate[1]))

    best_abs = [row["max_abs_r"] for row in pairwise.values()]
    manifest = {
        "schema_version": 1,
        "upstream_commit": "0a684b63ee0e4a401cb907a3827a82ea997d74c4",
        "matrix": {"n_models": len(models), "n_evaluations": len(evaluations), "n_observed": int(np.isfinite(matrix).sum())},
        "input": {"scores_sha256": hashlib.sha256(scores_path.read_bytes()).hexdigest()},
        "submatrix": {
            "largest_shape": [len(largest_rows), len(largest_columns)],
            "largest_stable_rank": largest_summary["stable_rank"],
            "target_evaluation_counts": [4, 7, 10, 13],
        },
        "correlation": {
            "min_shared": 5, "n_evaluations_with_neighbor": len(pairwise),
            "median_best_abs_r": float(np.median(best_abs)),
            "n_best_abs_r_at_least_0_85": sum(value >= 0.85 for value in best_abs),
        },
        "outputs": [
            "threshold_sweep.json", "threshold_sweep.tex", "stable_rank_results.json",
            "submatrix_sweep.json", "submatrix_sweep.tex", "pairwise_ols_stats.json",
            "correlation_mds.npz", "mds_coordinates.csv",
        ],
    }
    _write_json(OUTPUT / "manifest.json", manifest)
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
