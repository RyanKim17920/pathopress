#!/usr/bin/env python3
"""Build the pinned-BenchPress all-step rank-pruned pathology allowlist."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from pathopress.matrix import filter_matrix, load_scores, make_matrix  # noqa: E402
from pathopress.probe_compression import rank_prune_trajectory  # noqa: E402


UPSTREAM_REFERENCE_COMMIT = "0a684b63ee0e4a401cb907a3827a82ea997d74c4"
EVAL_PROTOCOL = "all_known_greedy_rank_pruning_v1"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scores", type=Path, default=ROOT / "data/scores.csv")
    parser.add_argument(
        "--source",
        type=Path,
        default=ROOT / "experiments/probe_selection_results_rank1.json",
    )
    parser.add_argument("--keep-count", type=int, default=30)
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "experiments/probe_pruning_rank1_top30.json",
    )
    parser.add_argument(
        "--allowlist-output",
        type=Path,
        default=ROOT / "data/error_informed_probe_allowlist_rank1_top30.json",
    )
    return parser.parse_args()


def relative(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(ROOT))
    except ValueError:
        return str(path.resolve())


def main() -> None:
    args = parse_args()
    _, _, evaluations = filter_matrix(*make_matrix(load_scores(args.scores)))
    source = json.loads(args.source.read_text(encoding="utf-8"))
    trajectory = source.get("all_known_greedy")
    if trajectory is None:
        trajectory = source["all_known"]["greedy_trajectory"]
    summary = rank_prune_trajectory(
        trajectory,
        evaluations,
        keep_count=args.keep_count,
        score_key="parity_medae",
    )
    config = {
        "eval_protocol": EVAL_PROTOCOL,
        "upstream_reference_commit": UPSTREAM_REFERENCE_COMMIT,
        "metric": "medae",
        "keep_fraction": None,
        "keep_count": args.keep_count,
        "source_steps_used": summary["source_steps_used"],
        "candidate_ids": evaluations,
        "candidate_hash": hashlib.sha256("\n".join(evaluations).encode()).hexdigest()[:12],
        "source_greedy_result_path": relative(args.source),
        "source_greedy_result_sha256": hashlib.sha256(args.source.read_bytes()).hexdigest(),
        "rank_direction": "lower score is better within each greedy context",
        "missing_after_selection": "Candidates selected by greedy are ranked only until their selected step; later contexts omit already-selected candidates.",
        "pathology_adaptation": "The pruning algorithm and 10-step/keep-30 budgets match the pinned upstream contract; evaluation IDs, matrix, and rank-1 predictor are pathology-specific.",
    }
    payload = {"schema_version": 1, "config": config, "summary": summary}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    allowlist = {
        "schema_version": 1,
        "name": "pathology_rank1_top30_count_by_greedy",
        "description": "Error-informed allowlist generated by aggregate normalized candidate rank across all 10 source MedAE greedy steps.",
        "source_result": relative(args.output),
        "source_greedy_result": relative(args.source),
        "pruning_config": config,
        "removed_evaluation_ids": summary["removed_ids"],
        "evaluation_ids": summary["kept_ids"],
        "error_informed": True,
    }
    args.allowlist_output.parent.mkdir(parents=True, exist_ok=True)
    args.allowlist_output.write_text(
        json.dumps(allowlist, indent=2) + "\n", encoding="utf-8"
    )
    print(
        f"wrote {args.output} and {args.allowlist_output}; "
        f"kept {len(summary['kept_ids'])}/{len(evaluations)} over "
        f"{summary['source_steps_used']} steps"
    )


if __name__ == "__main__":
    main()
